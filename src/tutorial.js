// A device preference: excluded from business backups and data revision tracking.
export async function shouldShowTutorial() {
  return (await db.meta.get('tutorial'))?.value?.dismissed !== true;
}
export async function completeTutorial() {
  await db.meta.put({ key: 'tutorial', value: { dismissed: true, dismissedAt: new Date().toISOString() } });
}
